# -*- coding: utf-8 -*-
"""
dataset.py — PyTorch Dataset for ULF-MRI Reconstruction
=========================================================

Loads HDF5 datasets generated by generate_dataset.py.
Returns (noisy_input, clean_target) pairs for training.
"""
from __future__ import annotations
import h5py
import numpy as np
import torch
from torch.utils.data import Dataset


class ULFMRIDataset(Dataset):
    """ULF-MRI reconstruction dataset.

    Parameters
    ----------
    h5_path : str
        Path to HDF5 file (train.h5, val.h5, or test.h5).
    input_type : str
        Which receiver to use as input: 'squid', 'coil', or 'both'.
        'both' stacks SQUID and coil as 2-channel input.
    augment : bool
        If True, apply random flips and 90° rotations (train only).
        Augmentation is applied identically to input and target.
    """

    def __init__(self, h5_path: str, input_type: str = 'squid',
                 augment: bool = False):
        if input_type not in ('squid', 'coil', 'both'):
            raise ValueError(f"input_type must be 'squid', 'coil', or 'both', got '{input_type}'")
        self.h5_path = h5_path
        self.input_type = input_type
        self.augment = augment

        with h5py.File(h5_path, 'r') as f:
            if 'images' in f:
                self.ideal = f['images/ideal'][:].astype(np.float32)
                self.squid = f['images/squid'][:].astype(np.float32)
                self.coil = f['images/coil'][:].astype(np.float32)
            else:
                self.ideal = f['ideal'][:].astype(np.float32)
                self.squid = f['squid'][:].astype(np.float32)
                self.coil = f['coil'][:].astype(np.float32)

    def __len__(self) -> int:
        return len(self.ideal)

    def __getitem__(self, idx: int):
        target = torch.from_numpy(self.ideal[idx]).unsqueeze(0)  # (1, H, W)

        if self.input_type == 'squid':
            inp = torch.from_numpy(self.squid[idx]).unsqueeze(0)
        elif self.input_type == 'coil':
            inp = torch.from_numpy(self.coil[idx]).unsqueeze(0)
        else:  # both
            inp = torch.from_numpy(
                np.stack([self.squid[idx], self.coil[idx]], axis=0))  # (2, H, W)

        # Data augmentation: random flips and 90° rotations
        # Applied identically to input and target
        if self.augment:
            if torch.rand(1).item() > 0.5:
                inp = torch.flip(inp, [-1])
                target = torch.flip(target, [-1])
            if torch.rand(1).item() > 0.5:
                inp = torch.flip(inp, [-2])
                target = torch.flip(target, [-2])
            k = torch.randint(0, 4, (1,)).item()
            if k > 0:
                inp = torch.rot90(inp, k, [-2, -1])
                target = torch.rot90(target, k, [-2, -1])

        return inp, target


if __name__ == "__main__":
    for split in ['train', 'val', 'test']:
        path = f"data/dataset/{split}.h5"
        for inp_type in ['squid', 'coil', 'both']:
            ds = ULFMRIDataset(path, input_type=inp_type)
            x, y = ds[0]
            ch = 2 if inp_type == 'both' else 1
            assert x.shape == (ch, 128, 128), f"Bad input shape: {x.shape}"
            assert y.shape == (1, 128, 128), f"Bad target shape: {y.shape}"
        print(f"  {split}: {len(ds)} samples ✓")
    print("  OK ✓")
